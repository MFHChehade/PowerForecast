"""Build compact LNN AI-data-center GPU-power parquets + suitability report.

Source: Mughees et al., "AI Data Center Load Forecasting: A Liquid Neural Network
Approach" (IEEE TSG, 2026). Public repo (MIT): github.com/Mariam-124/AI-LNN-based-STLF.

The repo ships only BASE SIGNATURES (one measured 1 Hz cycle each), NOT the long
7-day repeated/shuffled/scaled series used in the paper (that is regenerated by the
script from a `Shuffled_LLMs.csv` that is not shipped). We store the REAL signatures,
each as a single series, and flag the repeated/scaled construction honestly.

Outputs:
  extension_data/lnn_ai_datacenter/lnn_training_power.parquet
  extension_data/lnn_ai_datacenter/lnn_inference_power.parquet
  outputs_lnn_ai_datacenter_check/lnn_dataset_suitability.md
"""
from __future__ import annotations

from pathlib import Path

import sys as _sys
from pathlib import Path as _Path

_REPO = _Path(__file__).resolve().parents[2]
for _p in (str(_REPO), str(_REPO / "scripts")):
    if _p not in _sys.path:
        _sys.path.insert(0, _p)

from powerforecast import config

import numpy as np
import pandas as pd

EXT = config.EXTENSION_ROOT / "lnn_ai_datacenter"
RAW = EXT / "raw"
OUT = config.OUTPUTS_ROOT / "outputs_lnn_ai_datacenter_check"
ORIGIN = pd.Timestamp("2026-01-01")
CONTEXTS = [100, 300, 600]
HORIZON_PROBE = 48  # representative horizon for support test


def load_signature(fname, power_col, series_id, workload_type):
    d = pd.read_excel(RAW / fname, sheet_name="Sheet2")
    sec = pd.to_numeric(d["seconds"], errors="coerce").to_numpy()
    p = pd.to_numeric(d[power_col], errors="coerce").to_numpy(float)
    m = np.isfinite(sec) & np.isfinite(p)
    sec, p = sec[m], p[m]
    ts = ORIGIN + pd.to_timedelta(sec.astype(float), unit="s")
    return pd.DataFrame({
        "timestamp": ts,
        "power_watts": p.astype(np.float64),
        "power_mw": (p / 1e6).astype(np.float64),
        "series_id": series_id,
        "workload_type": workload_type,
        "source_dataset": "lnn_ai_datacenter",
        "sampling_interval_seconds": 1.0,
    })


def stats(df):
    v = df["power_watts"].to_numpy(float)
    n = len(v)
    ac1 = float(np.corrcoef(v[:-1], v[1:])[0, 1]) if n > 2 and v.std() > 0 else np.nan
    vol = float(np.abs(np.diff(v)).mean() / v.std()) if v.std() > 0 else 0.0
    return n, ac1, vol, float(v.min()), float(v.max()), float(v.mean())


def main():
    OUT.mkdir(parents=True, exist_ok=True)
    tr = load_signature("Train_signature.xlsx", "Total GPU Power (W)", "lnn_training_signature", "training")
    inf = load_signature("Infer_signature.xlsx", "Actual GPU Power (W)", "lnn_inference_signature", "inference")
    tr.to_parquet(EXT / "lnn_training_power.parquet", index=False)
    inf.to_parquet(EXT / "lnn_inference_power.parquet", index=False)

    ntr, ac_tr, vol_tr, lo_tr, hi_tr, mu_tr = stats(tr)
    ninf, ac_inf, vol_inf, lo_inf, hi_inf, mu_inf = stats(inf)

    def support(n):
        return {c: bool(n >= c + HORIZON_PROBE + 1) for c in CONTEXTS}, {c: max(0, n - c - HORIZON_PROBE + 1) for c in CONTEXTS}

    sup_tr, win_tr = support(ntr)
    sup_inf, win_inf = support(ninf)

    md = f"""# LNN AI Data Center — GPU-Power Dataset Suitability

**Source:** Mughees et al., *AI Data Center Load Forecasting: A Liquid Neural Network Approach*, IEEE Transactions on Smart Grid (2026). Repo: https://github.com/Mariam-124/AI-LNN-based-STLF (**public, MIT license**, ~49 KB).

## What the repo actually ships
- `Train_signature.xlsx` (Sheet2): 852 rows — columns `seconds`, `Total GPU Power (W)`.
- `Infer_signature.xlsx` (Sheet2): 550 rows — columns `seconds`, `Actual GPU Power (W)`.
- `LNN_forecaster.py`: a meta-script that emits a CfC forecaster expecting `Shuffled_LLMs.csv` (column `Avg GPU Power (W)`, ×20,000 scaling, LOOKBACK=100, HORIZON=1). **That shuffled/long CSV is NOT in the repo.**
- `Data`: 1-byte placeholder (empty). `LICENSE`: MIT.

**Conclusion on availability:** repo is public and accessible; only the **base measured signatures** (one cycle each) are stored. The long **7-day, repeated/shuffled, 150 MW-scaled** series used in the paper is **regenerated**, not stored.

## Data nature (honest classification)
| Trace | Stored content | Nature | Units | Cadence | Duration |
|---|---|---|---|---|---|
| Training | 852-sample signature | **real measured** 8×H100 node power (GPT-2 124M), one cycle | W (node scale ~2.3–5.6 kW) | 1 Hz | 852 s (~14.2 min) |
| Inference | 550-sample signature | **real measured but already MW-scaled** (19-LLM signature) | W (≈11.7–57.5 MW) | 1 Hz | 550 s (~9.2 min) |

- The paper's published benchmark series are **repeated (7-day tiling) + probabilistically shuffled + scaled (α/β) to a 150 MW envelope** — i.e. **semi-synthetic / processed**, NOT a pure operational trace. Per the task guidance, the tiled/scaled version must not be treated as independent operational data (tiling produces near-duplicate windows and an artificially periodic, easy task).

## Series statistics (on the real signatures)
| Trace | rows | min (W) | max (W) | mean (W) | lag-1 autocorr | volatility (mean\\|Δ\\|/std) |
|---|---|---|---|---|---|---|
| Training | {ntr} | {lo_tr:.0f} | {hi_tr:.0f} | {mu_tr:.0f} | {ac_tr:.4f} | {vol_tr:.4f} |
| Inference | {ninf} | {lo_inf:.3g} | {hi_inf:.3g} | {mu_inf:.3g} | {ac_inf:.4f} | {vol_inf:.4f} |

Both are **genuinely volatile** (training especially: lag-1 0.35, volatility 0.21) — far more dynamic than Google PowerData (lag-1 0.997) or NLR inference (volatility 0.003). This is the volatile-AI-power regime where foundation models tend to help.

## Context support at 1 Hz (single signature, horizon={HORIZON_PROBE})
| context (s) | training supported? | training windows | inference supported? | inference windows |
|---|---|---|---|---|
| 100 | {sup_tr[100]} | {win_tr[100]} | {sup_inf[100]} | {win_inf[100]} |
| 300 | {sup_tr[300]} | {win_tr[300]} | {sup_inf[300]} | {win_inf[300]} |
| 600 | {sup_tr[600]} | {win_tr[600]} | {sup_inf[600]} | {win_inf[600]} |

- **Training** (852 s) supports contexts 100/300/600 — but as a SINGLE short series the window counts are small (esp. at 600).
- **Inference** (550 s) supports 100/300 but **NOT 600** (600+48 > 550).
- The repeated 7-day series would "support" everything, but only via duplicate/periodic windows — not honest forecasting evidence.

## Suitability verdict
- **Real measured power?** Yes for the underlying signatures (1 Hz GPU telemetry); inference is real-but-already-MW-scaled. The long benchmark series is repeated/shuffled/scaled (semi-synthetic).
- **Train/inference split:** available (two separate signature files).
- **Recommended role: APPENDIX / AI-workload GPU-power benchmark (with caveats), not a main operational dataset.**
  - Valuable as a **short, volatile, real AI-GPU-power example** that reinforces the volatility-boundary story (training signature is highly dynamic).
  - Not suitable as a main long-horizon operational trace: each real signature is only ~9–14 min; the long version is tiled/scaled, so it cannot stand in for an independent multi-day operational dataset.
  - If used in a pilot: use the **single real signatures** (training for ctx 100/300/600; inference for ctx 100/300 only), keep training and inference as separate series, and do NOT use the repeated/scaled 150 MW series as independent data.
- **Do not** present the 150 MW / 7-day figures as measured operational data — they are a scaled, repeated emulation of a hyperscale envelope built from short real signatures.

_Generated by build_lnn_dataset.py._
"""
    (OUT / "lnn_dataset_suitability.md").write_text(md, encoding="utf-8")

    print(f"training parquet: {ntr} rows -> {EXT/'lnn_training_power.parquet'}")
    print(f"inference parquet: {ninf} rows -> {EXT/'lnn_inference_power.parquet'}")
    print(f"training lag1ac={ac_tr:.3f} vol={vol_tr:.3f} range={lo_tr:.0f}-{hi_tr:.0f}W")
    print(f"inference lag1ac={ac_inf:.3f} vol={vol_inf:.3f} range={lo_inf/1e6:.2f}-{hi_inf/1e6:.2f}MW")
    print(f"context support training={sup_tr} inference={sup_inf}")
    print(f"wrote {OUT/'lnn_dataset_suitability.md'}")


if __name__ == "__main__":
    main()
